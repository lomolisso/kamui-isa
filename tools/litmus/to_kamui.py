#!/usr/bin/env python3
"""Lower the PTX litmus tests to Kamui and translate the Kamui tests into Alloy queries against the Kamui model.

    python tools/litmus/to_kamui.py              # write tests/litmus/kamui-isa/{kamui,std}/ and tests/litmus/alloy-kamui/
    python tools/litmus/to_kamui.py --check      # fail if a committed file is missing, stale or orphaned
    python tools/litmus/to_kamui.py --why        # every test it cannot lower or translate, with the reason
    python tools/litmus/to_kamui.py --rules      # how many instructions each lowering rule handled
    python tools/litmus/to_kamui.py --broken R   # lower with the broken rule R and look for a counterexample

Two steps, written from two tables that are kept separate on purpose:

1. **Lowering** (models/kamui/lowering.yaml): every instruction of a PTX test becomes Kamui instructions. The
   variant `kamui` uses Kamui instructions only; the variant `std` uses, wherever lowering.yaml lists one, the
   standard RISC-V instruction a compiler may use instead (exact or stronger). The result is a Kamui litmus test
   (`KAMUI` dialect, tests/litmus/kamui-isa/<variant>/<test>.litmus). Location spaces, which PTX tests imply
   through their instructions, are written out in the initial state (`x in shared cta 1`), because a generic
   Kamui access does not name its space.
2. **Meaning** (models/kamui/instructions.yaml): every Kamui or standard instruction is replaced by the PTX
   operation whose events it produces, and the result is translated by tools/litmus/to_alloy87.py into a query
   against models/kamui/kamui.als (tests/litmus/alloy-kamui/<variant>/<test>.als).

tools/litmus/run_formal.py runs the queries (models `kamui-alloy` and `kamui-std-alloy`) and
tools/litmus/check_suite.py checks that no lowered test allows an outcome PTX 8.7 forbids. Hand-written Kamui
tests (tests/litmus/kamui-isa/hand/) skip step 1.
"""

from __future__ import annotations

import argparse
import functools
import re
import shutil
import subprocess
import sys
import tempfile
from collections import Counter
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import litmus  # noqa: E402
import to_alloy87  # noqa: E402
from to_alloy87 import Unsupported  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SUITE = ROOT / "tests" / "litmus"
KTESTS = SUITE / "kamui-isa"
OUT = SUITE / "alloy-kamui"
MODEL = ROOT / "models" / "kamui"
VARIANTS = ("kamui", "std")
MODEL_NAMES = {"kamui": "kamui-alloy", "std": "kamui-std-alloy", "hand": "kamui-alloy"}
HEADER = "// Generated by tools/litmus/to_kamui.py from tests/litmus/{test}.litmus. Do not edit.\n"

SCOPES = set(litmus.SCOPES)
SPACE_WORDS = {"global", "shared", "shared::cta", "shared::cluster", "local", "const", "param"}
ORDERS = {"weak", "relaxed", "acquire", "release", "acq_rel", "sc", "volatile"}
# qualifiers that are performance hints or only say "the whole warp executes this": dropped (D27)
DROP = re.compile(r"^(ca|cg|cs|lu|cv|wb|wt|L1::.*|L2::.*|level::.*|aligned|sync|unified|evict_.*|noftz)$")
TYPE = re.compile(r"^([busf](8|16|32|64|128)|f16x2|bf16|bf16x2|e4m3|e5m2|tf32|b1024|v\d)$")
GRAPHICS = {"tld", "suld", "sust", "suatom", "sured", "cold"}
AMO_OPS = {"add": "add", "and": "and", "or": "or", "xor": "xor", "min": "min", "max": "max", "exch": "swap"}
FLOAT = re.compile(r"^(f16|f16x2|bf16|bf16x2|f32|f64)$")


def load_rules() -> dict:
    return {r["id"]: r for r in yaml.safe_load((MODEL / "lowering.yaml").read_text())["rules"]}


@functools.cache
def load_meanings() -> dict[str, str]:
    """Kamui mnemonic (with its fixed qualifiers) -> the PTX operation it produces (instructions.yaml)."""
    rows = yaml.safe_load((MODEL / "instructions.yaml").read_text())["kamui"]
    return {r["name"]: r["events"] for r in rows}


# ================================================================================================ lowering


class Lowerer:
    """Lowers one PTX test. `used` counts the rules applied."""

    def __init__(self, t: litmus.Litmus, variant: str, broken: str | None = None, src: str = "?"):
        self.t, self.variant, self.broken, self.src = t, variant, broken, src
        self.used: Counter = Counter()
        self.nreg = 0

    def rule(self, rid: str):
        self.used[rid] += 1

    def std(self) -> bool:
        return self.variant == "std"

    def lower_test(self) -> str:
        t = self.t
        for _, i in t.instrs():
            if i.op in GRAPHICS or (i.op == "fence" and i.quals[:2] in (["proxy", "texture"], ["proxy", "surface"],
                                                                        ["proxy", "constant"])):
                raise Unsupported("texture, surface and constant-proxy instructions of the PTX 7.5 tests: not PTX 8.7, "
                                  "and outside Kamui (graphics)")
        q = to_alloy87.Query(t, "probe")
        q.pdirs, q.pspace, q.paddr, q.txops, q.open_arrive = {}, {}, {}, {}, {}
        q.build()  # resolves the space and owner of every location, as PTX implies them
        decl = []
        inv_cta = {atom: key for key, atom in q.cta_id.items()}
        for loc in q.locs.values():
            if loc.alias_of or loc.members is not None:
                continue
            if loc.space == "Shared" and loc.owner:
                decl.append(f"{loc.name} in shared cta {inv_cta[loc.owner][2]}")
            elif loc.space == "Local" and loc.owner:
                decl.append(f"{loc.name} in local {loc.owner.replace('T', 'P')}")
            elif loc.space in ("Global", "Const", "Param"):
                decl.append(f"{loc.name} in {loc.space.lower()}")
        cols = []
        for th in t.threads:
            out = []
            self.seen_sc = False  # a fence.sc earlier in the thread (D44)
            for ins in th.instrs:
                if ins.is_empty:
                    continue
                out += self.lower(ins)
            cols.append([th.placement] + out)
        nrows = max(len(c) for c in cols)
        for c in cols:
            c.extend([""] * (nrows - len(c)))
        widths = [max(len(x) for x in c) for c in cols]
        lines = [f"KAMUI {t.name}"]
        variant_note = {"kamui": "Kamui instructions only", "std": "standard RISC-V instructions where allowed"}
        lines.append(f'"Lowered from tests/litmus/{self.src}.litmus by tools/litmus/to_kamui.py '
                     f'({variant_note[self.variant]}). Generated: do not edit."')
        lines.append("{")
        lines += [f"{d};" for d in list(t.init) + decl]
        lines.append("}")
        for r in range(nrows):
            lines.append(" " + " | ".join(cols[k][r].ljust(widths[k]) for k in range(len(cols))) + " ;")
        lines.append(t.quantifier)
        lines.append(f"({t.cond_text})" if not t.cond_text.startswith("(") else t.cond_text)
        return "\n".join(lines) + "\n"

    # ------------------------------------------------------------------------------------------- helpers

    @staticmethod
    def keep(quals) -> list[str]:
        return [x for x in quals if not DROP.match(x)]

    @staticmethod
    def k(mn: str, quals, args) -> str:
        head = ".".join([mn] + [x for x in quals if x])
        return f"{head} {', '.join(args)}" if args else head

    def fresh(self) -> str:
        self.nreg += 1
        return f"rk{self.nreg}"

    # ------------------------------------------------------------------------------------------- rules

    def lower(self, ins: litmus.Instr) -> list[str]:
        op, q, a = ins.op, self.keep(ins.quals), list(ins.args)
        if op == "ld" and not ins.quals and len(a) == 2 and to_alloy87._const(a[1]) is not None:
            return [f"li {a[0]}, {a[1]}"]
        if op in ("add", "sub", "mul"):
            return [ins.text]
        if op in ("ld", "ldu"):
            return self.load(ins, q, a)
        if op == "st" and "async" not in q:
            return self.store(ins, q, a)
        if op == "atom":
            return self.atom(ins, q, a)
        if op == "red" and "async" not in q:
            return self.red(ins, q, a)
        if op in ("fence", "membar"):
            return self.fence(ins, q, a)
        if op == "bar" or (op == "barrier" and q[:1] != ["cluster"]):
            return self.bar(ins, q, a)
        if op == "barrier":
            self.rule("barrier.cluster")
            if "arrive" in q:
                return ["kcgabar.arv.relaxed" if "relaxed" in q else "kcgabar.arv.release"]
            return ["kcgabar.wait.acquire"]
        if op == "mbarrier":
            return self.mbarrier(ins, q, a)
        if op == "cp":
            return self.cp(ins, q, a)
        if op == "st" or op == "red":
            return self.async_store(ins, q, a)
        if op == "griddepcontrol":
            self.rule("griddepcontrol")
            return ["kacqbulk"] if q == ["wait"] else ["kpreexit"]
        if op == "tensormap":
            return self.tensormap(ins, q, a)
        if op == "wgmma":
            self.rule("wgmma")
            kind = q[0] if q else ""
            if kind == "fence":
                return ["kwarpgroup.arrive"]
            if kind == "commit_group":
                return ["kwarpgroup.commit"]
            if kind == "wait_group":
                return [self.k("kwarpgroup.depbar", [], a)]
            return [self.k("kgmma", q[1:], a)]
        if op in ("ldmatrix", "stmatrix"):
            self.rule("ldmatrix")
            rest = [x for x in q if x not in ("shared", "shared::cta", "b16")]
            return [self.k("kldsm" if op == "ldmatrix" else "kstsm", rest, a)]
        if op == "multimem":
            self.rule("multimem")
            kind, rest = q[0], [x for x in q[1:] if x != "global"]
            mn = {"ld_reduce": "kldgmc", "st": "kstgmc", "red": "kredgmc"}[kind]
            return [self.k(mn, rest, a)]
        if op == "discard":
            self.rule("discard")
            return [f"cbo.inval {a[0]}"] if self.std() else [self.k("kcctl.rml2", [], a)]
        if op in ("prefetch", "prefetchu", "applypriority", "createpolicy"):
            self.rule("hints")
            if op in ("prefetch", "prefetchu") and "tensormap" not in q:
                return [f"prefetch.r {a[0]}"]
            if "tensormap" in q:
                return [f"ktmacctl.pf {a[0]}"]
            return []
        raise Unsupported(f"no lowering rule for {ins.text!r}")

    def space(self, q) -> str | None:
        return next((x for x in q if x in SPACE_WORDS), None)

    def strip(self, q, *drop) -> list[str]:
        return [x for x in q if x not in SPACE_WORDS and x not in drop]

    def load(self, ins, q, a) -> list[str]:
        sp = self.space(q)
        if ins.op == "ldu":
            self.rule("ldu")
            return [self.k("kldg.weak", [x for x in q if TYPE.match(x)], a)]
        rest = self.strip(q)
        if "volatile" in rest:
            self.rule("ld.volatile")
            rest = ["relaxed", "sys"] + [x for x in rest if x != "volatile"]
        elif "mmio" in rest:
            self.rule("ld.mmio")
        elif "nc" in rest:
            self.rule("ld.global.nc")
        else:
            self.rule({None: "ld", "global": "ld.global", "shared": "ld.shared", "shared::cta": "ld.shared",
                       "shared::cluster": "ld.shared::cluster", "local": "ld.local", "const": "ld.const",
                       "param": "ld.param"}[sp])
        if self.broken == "ld-acquire" and "acquire" in rest:
            rest = ["relaxed" if x == "acquire" else x for x in rest]
        order = next((x for x in rest if x in ORDERS), "weak")
        vec = any(re.fullmatch(r"v\d", x) for x in rest)
        if self.std() and not vec and "mmio" not in rest and "nc" not in rest and sp not in ("const", "param"):
            if order == "weak":
                return [self.k("ld" if any(x in rest for x in ("b64", "u64", "s64")) else "lw", [], a)]
            if order == "acquire":
                return [self.k("lw.aq", [], a)]
        mn = {None: "kld", "global": "kldg", "shared": "klds", "shared::cta": "klds", "shared::cluster": "kld",
              "local": "kldl", "const": "kldc.const", "param": "kldc.param"}[sp]
        return [self.k(mn, rest, a)]

    def store(self, ins, q, a) -> list[str]:
        sp = self.space(q)
        rest = self.strip(q)
        if "volatile" in rest:
            self.rule("st.volatile")
            rest = ["relaxed", "sys"] + [x for x in rest if x != "volatile"]
        elif "mmio" in rest:
            self.rule("st.mmio")
        else:
            self.rule({None: "st", "global": "st.global", "shared": "st.shared", "shared::cta": "st.shared",
                       "shared::cluster": "st.shared::cluster", "local": "st.local"}.get(sp, "st.param"))
        order = next((x for x in rest if x in ORDERS), "weak")
        vec = any(re.fullmatch(r"v\d", x) for x in rest)
        if self.std() and not vec and "mmio" not in rest:
            if order == "weak":
                return [self.k("sd" if any(x in rest for x in ("b64", "u64", "s64")) else "sw", [], a)]
            if order == "release":
                return [self.k("sw.rl", [], a)]
        mn = {None: "kst", "global": "kstg", "shared": "ksts", "shared::cta": "ksts", "shared::cluster": "kst",
              "local": "kstl"}[sp]
        return [self.k(mn, rest, a)]

    def amo(self, q, a, is_red) -> list[str] | None:
        """The standard AMO for an atomic or reduction, or None when there is none."""
        rop = next((x for x in q if x in to_alloy87.RMW_OPS), None)
        if any(FLOAT.match(x) for x in q) or any(re.fullmatch(r"v\d", x) for x in q):
            return None
        order = next((x for x in q if x in ORDERS), "relaxed")
        suffix = {"relaxed": "", "acquire": ".aq", "release": ".rl", "acq_rel": ".aqrl"}[order]
        width = "q" if "b128" in q else "d" if any(x in q for x in ("b64", "u64", "s64")) else \
            "h" if any(x in q for x in ("b16", "u16", "s16")) else "w"
        args = (["x0"] + a) if is_red else a
        if rop == "cas":
            return [f"amocas.{width}{suffix} {', '.join(args)}"]
        if rop in AMO_OPS and width != "q":
            return [f"amo{AMO_OPS[rop]}.{width}{suffix} {', '.join(args)}"]
        return None

    def atom(self, ins, q, a) -> list[str]:
        self.rule("atom")
        if getattr(self, "seen_sc", False) and next((x for x in q if x in ORDERS), "relaxed") == "relaxed":
            # a relaxed atom after a fence.sc of its thread also acquires (D44): lower it as an acquire
            q = ["acquire" if x == "relaxed" else x for x in q]
            if "acquire" not in q:
                q = ["acquire"] + q
        sp = self.space(q)
        rest = self.strip(q)
        if self.std():
            s = self.amo(q, a, False)
            if s:
                return s
        mn = {None: "katom", "global": "katomg", "shared": "katoms", "shared::cta": "katoms",
              "shared::cluster": "katom"}[sp]
        return [self.k(mn, rest, a)]

    def red(self, ins, q, a) -> list[str]:
        sp = self.space(q)
        rest = self.strip(q)
        order = next((x for x in rest if x in ORDERS), "relaxed")
        if self.std():
            s = self.amo(q, a, True)
            if s:
                self.rule("red")
                return s
        if order in ("acquire", "acq_rel"):
            self.rule("red.acq_rel")
            mn = {None: "katom", "global": "katomg", "shared": "katoms", "shared::cta": "katoms",
                  "shared::cluster": "katom"}[sp]
            return [self.k(mn, rest, ["RZ"] + a)]
        self.rule("red")
        if sp in ("shared", "shared::cta"):
            return [self.k("katoms", rest, ["RZ"] + a)]
        if sp == "shared::cluster":
            return [self.k("katom", rest, ["RZ"] + a)]
        return [self.k("kredg" if sp == "global" else "kred", rest, a)]

    def fence(self, ins, q, a) -> list[str]:
        if ins.op == "membar":
            if q == ["proxy", "alias"]:
                self.rule("fence.proxy.alias")
                return ["kfence.proxy.alias"]
            self.rule("membar")
            self.seen_sc = True
            s = {"gl": "gpu"}.get(q[0], q[0])
            if self.broken == "fence-scope" and s in ("gpu", "sys"):
                s = "cta"
            return ["fence rw, rw"] if self.std() else [f"kfence.sc.{s}"]
        if q[:1] == ["proxy"]:
            kind = q[1:]
            if kind == ["alias"]:
                self.rule("fence.proxy.alias")
                return ["kfence.proxy.alias"]
            if kind[:1] == ["async"]:
                self.rule("fence.proxy.async")
                if self.broken == "proxy-async":
                    return []
                sp = {"global": ".global", "shared::cta": ".shared_cta", "shared::cluster": ".shared_cluster"}
                return ["kfence.proxy.async" + (sp[kind[1]] if len(kind) > 1 else "")]
            if kind[:1] == ["async::generic"]:
                self.rule("fence.proxy.async.restrict")
                return ["kfence.proxy.async.restrict.shared_cluster.acquire.cluster"]
            if kind[:1] == ["tensormap::generic"]:
                self.rule("fence.proxy.tensormap")
                s = next(x for x in kind if x in SCOPES)
                return [self.k(f"kfence.proxy.tensormap.{kind[1]}.{s}", [], a)]
            raise Unsupported(f"no lowering rule for {ins.text!r}")
        if "mbarrier_init" in q:
            self.rule("fence.restrict")
            return ["kfence.restrict.mbarrier_init.release.cluster"]
        restrict = [x for x in q if x.startswith("sync_restrict")]
        if restrict:
            self.rule("fence.restrict")
            if self.broken == "restrict":
                return []
            return ["kfence.restrict.shared_cta.release.cluster" if "sync_restrict::shared::cta" in restrict
                    else "kfence.restrict.shared_cluster.acquire.cluster"]
        self.rule("fence")
        sem = next((x for x in q if x in ("sc", "acq_rel", "acquire", "release")), "acq_rel")
        if sem == "sc":
            self.seen_sc = True
        s = next(x for x in q if x in SCOPES)
        if self.broken == "fence-scope" and s in ("gpu", "sys"):
            s = "cta"
        if self.std():
            return [{"sc": "fence rw, rw", "acq_rel": "fence.tso", "acquire": "fence r, rw",
                     "release": "fence rw, w"}[sem]]
        return [f"kfence.{sem}.{s}"]

    def bar(self, ins, q, a) -> list[str]:
        q = [x for x in ins.quals if x not in ("aligned",)]
        if q[:2] == ["warp", "sync"]:
            self.rule("bar.warp.sync")
            return [self.k("kwarpsync", [], a)]
        if "red" in q:
            self.rule("bar.red")
            return [self.k("kbar.red", [x for x in q if x in ("popc", "and", "or")], a)]
        if ins.op == "bar" and q[:1] == ["cta"]:   # Dat3M: bar.cta.sync i[, a[, b]]
            mode = q[1:]
            args = [a[1] if len(a) > 1 else a[0]] + a[2:]
        else:
            mode = [x for x in q if x != "cta"]
            args = a
        if mode[:1] == ["arrive"]:
            self.rule("bar.arrive")
            return [self.k("kbar.arv", [], args)]
        self.rule("bar.sync")
        return [self.k("kbar.sync", [], args)]

    def mbarrier(self, ins, q, a) -> list[str]:
        self.rule("mbarrier")
        kind = q[0]
        rest = q[1:]
        name = {"init": "kmbar.init", "inval": "kmbar.inval", "arrive": "kmbar.arv", "arrive_drop": "kmbar.arv.drop",
                "expect_tx": "kmbar.expect_tx", "complete_tx": "kmbar.complete_tx", "test_wait": "kmbar.test",
                "try_wait": "kmbar.try"}[kind]
        if kind == "arrive" and rest[:1] == ["expect_tx"]:
            name, rest = "kmbar.arv.expect_tx", rest[1:]
        remote = "shared::cluster" in rest
        rest = [x for x in rest if x not in ("shared", "shared::cta", "shared::cluster", "b64")]
        if self.broken == "mbar-relaxed" and kind.startswith("arrive"):
            rest = ["relaxed" if x == "release" else x for x in rest]
            if "relaxed" not in rest:
                rest = ["relaxed"] + rest
        return [self.k(name, rest + (["remote"] if remote else []), a)]

    def cp(self, ins, q, a) -> list[str]:
        if q[:1] == ["reduce"]:
            return self.bulk(ins, q, a, reduce=True)
        rest = q[1:]  # after "async"
        if rest == ["commit_group"]:
            self.rule("cp.async.commit_group")
            return ["kldgdepbar"]
        if rest == ["wait_group"]:
            self.rule("cp.async.wait_group")
            return [self.k("kdepbar.ldgsts", [], a)]
        if rest == ["wait_all"]:
            self.rule("cp.async.wait_all")
            return ["kldgdepbar", "kdepbar.ldgsts 0"]
        if rest == ["bulk", "commit_group"]:
            self.rule("cp.async.bulk.commit_group")
            return ["ktmacmdflush"]
        if rest[:2] == ["bulk", "wait_group"]:
            self.rule("cp.async.bulk.wait_group")
            return [self.k("kdepbar.bulk", rest[2:], a)]
        if rest[:2] == ["mbarrier", "arrive"]:
            self.rule("cp.async.mbarrier.arrive")
            return [self.k("kmbar.arv.ldgsts", [x for x in rest[2:] if x == "noinc"], a)]
        if rest[:2] == ["bulk", "prefetch"]:
            self.rule("hints")
            return [f"ktmacctl.pf {a[0]}"]
        if rest[:1] == ["bulk"]:
            return self.bulk(ins, q, a, reduce=False)
        self.rule("cp.async")
        return [self.k("kldgsts", [], a)]

    def bulk(self, ins, q, a, reduce) -> list[str]:
        rest = q[3:] if reduce else q[2:]
        tensor = bool(rest) and rest[0] == "tensor"
        mc = ["mc"] if "multicast::cluster" in rest else []
        spaces = [x for x in rest if x in SPACE_WORDS]
        direction = {("shared::cluster", "global"): "s.g", ("shared::cluster", "shared::cta"): "s.s",
                     ("global", "shared::cta"): "g.s"}[tuple(spaces)]
        rop = [x for x in rest if x in to_alloy87.RMW_OPS]
        types = [x for x in rest if TYPE.match(x)]
        if tensor:
            dim = [x for x in rest if re.fullmatch(r"\dd", x)]
            mode = [x for x in rest if x in ("tile", "im2col")]
            if reduce:
                self.rule("cp.reduce.async.bulk.tensor")
                return [self.k("ktmaredg", dim + rop + mode, a)]
            self.rule("cp.async.bulk.tensor")
            return [self.k("ktmaldg" if direction == "s.g" else "ktmastg", dim + mode + mc, a)]
        if reduce:
            self.rule("cp.reduce.async.bulk")
            return [self.k("kblkred.g.s", rop + types, a)]
        self.rule("cp.async.bulk")
        return [self.k(f"kblkcp.{direction}", mc, a)]

    def async_store(self, ins, q, a) -> list[str]:
        rest = [x for x in q if x not in ("async", "global", "shared::cluster", "mbarrier::complete_tx::bytes")]
        if ins.op == "st":
            self.rule("st.async")
            return [self.k("kstas", rest, a)]
        self.rule("red.async")
        rop = [x for x in rest if x in to_alloy87.RMW_OPS]
        return [self.k("kredas", rop + [x for x in rest if x not in rop], a)]

    def tensormap(self, ins, q, a) -> list[str]:
        if q[:1] == ["replace"]:
            self.rule("tensormap.replace")
            return [f"sw {a[0]}, {a[1]}"] if self.std() else [f"kstg.weak {a[0]}, {a[1]}"]
        self.rule("tensormap.cp_fenceproxy")
        s = next(x for x in q if x in SCOPES)
        r = self.fresh()
        return [f"klds.weak {r}, {a[1]}", f"kstg.weak {a[0]}, {r}", f"kfence.proxy.tensormap.release.{s}"]


