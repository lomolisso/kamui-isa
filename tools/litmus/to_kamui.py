BROKEN = {
    "ld-acquire": "acquire loads lowered as relaxed loads",
    "fence-scope": "gpu and sys fences lowered at cta scope",
    "mbar-relaxed": "mbarrier arrives lowered without release",
    "proxy-async": "fence.proxy.async dropped",
    "restrict": "restricted (sync_restrict) fences dropped",
}


def run_alloy(query: str, workdir: Path) -> bool | None:
    """True when the outcome is allowed (the query's `test` run is SAT)."""
    home = Path("/opt/alloy/alloy-6.2.0")
    with tempfile.TemporaryDirectory(dir=workdir) as w:
        for f in ("kamui.als", "util.als"):
            shutil.copyfile(MODEL / f if f == "kamui.als" else ROOT / "models" / "ptx87" / f, Path(w) / f)
        (Path(w) / "q.als").write_text(query)
        p = subprocess.run(["java", f"-Djava.io.tmpdir={w}", f"-Djava.library.path={home / 'lib/runtime/lib'}",
                            "-jar", str(home / "lib/app/org.alloytools.alloy.dist.jar"), "exec", "-n", "-s",
                            "glucose", "-c", "test", "-f", "-o", str(Path(w) / "out"), "q.als"],
                           cwd=w, capture_output=True, text=True, timeout=3600)
    m = re.search(r"\d+\.\s+run\s+test\b[^\n]*?\b(UNSAT|SAT)\b", p.stdout + p.stderr)
    return None if not m else m.group(1) == "SAT"


def broken(rule: str) -> int:
    """Lower every test that PTX 8.7 forbids with a broken rule; report the tests whose outcome becomes allowed."""
    import csv
    from concurrent.futures import ThreadPoolExecutor
    rows = list(csv.DictReader(open(SUITE / "expected.csv", newline="", encoding="utf-8")))
    forbidden = {r["test"] for r in rows if r["model"] == to_alloy87.MODEL_NAME and r["result"] == "forbidden"}
    jobs = []
    for p in ptx_tests():
        tid = tid_of(p)
        if tid not in forbidden:
            continue
        t = litmus.load(p)
        try:
            text, _ = lower(t, "kamui", rule, tid)
            ok, _ = lower(t, "kamui", src=tid)
        except Unsupported:
            continue
        if text == ok:
            continue  # the broken rule does not touch this test
        try:
            jobs.append((tid, translate_kamui(litmus.parse(text), "broken", tid)))
        except Unsupported:
            continue
    work = ROOT / "build" / "litmus" / "kamui-broken"
    work.mkdir(parents=True, exist_ok=True)
    with ThreadPoolExecutor(32) as ex:
        res = list(ex.map(lambda j: (j[0], run_alloy(j[1], work)), jobs))
    caught = sorted(tid for tid, allowed in res if allowed)
    print(f"broken rule {rule} ({BROKEN[rule]}): {len(jobs)} forbidden tests affected, {len(caught)} now allowed")
    for tid in caught[:20]:
        print(f"  {tid}")
    return 0 if caught else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--why", action="store_true")
    ap.add_argument("--rules", action="store_true")
    ap.add_argument("--broken", choices=sorted(BROKEN))
    a = ap.parse_args()
    if a.broken:
        return broken(a.broken)
    files, skipped, used = generate()
    if a.why:
        for tid, why in sorted(skipped.items()):
            print(f"{tid}: {why}")
        return 0
    rules = load_rules()
    unknown = set(used) - set(rules)
    if unknown:
        print(f"rules used but not in lowering.yaml: {sorted(unknown)}")
        return 1
    if a.rules:
        for rid in rules:
            print(f"{used.get(rid, 0):6}  {rid}")
        return 0
    roots = [KTESTS / v for v in VARIANTS] + [OUT]
    existing = {p for r in roots if r.exists() for p in r.rglob("*") if p.suffix in (".litmus", ".als")}
    if a.check:
        bad = [p for p, s in files.items() if not p.exists() or p.read_text() != s]
        extra = sorted(existing - set(files))
        for p in bad:
            print(f"stale or missing: {p.relative_to(ROOT)}")
        for p in extra:
            print(f"orphaned: {p.relative_to(ROOT)}")
        print(f"{len(files)} files, {len(bad)} stale, {len(extra)} orphaned, {len(skipped)} skipped")
        return 1 if bad or extra else 0
    for p in existing - set(files):
        p.unlink()
    for p, s in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(s)
    print(f"wrote {len(files)} files, skipped {len(skipped)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
