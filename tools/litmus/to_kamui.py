FENCE_RW = re.compile(r"^[iorw]+$")


def fence_kind(pred: str, succ: str) -> str:
    """K3: i counts as r, o as w."""
    p = set(pred.replace("i", "r").replace("o", "w"))
    s = set(succ.replace("i", "r").replace("o", "w"))
    if "w" in p and "r" in s:
        return "fence.sc.sys"
    if p == {"r"}:
        return "fence.acquire.sys"
    if s == {"w"}:
        return "fence.release.sys"
    return "fence.acq_rel.sys"


class Expander:
    """Replaces every Kamui or standard instruction by the PTX operation(s) whose events it produces."""

    def __init__(self):
        self.meaning = load_meanings()
        self.names = sorted(self.meaning, key=lambda n: -n.count("."))

    def std(self, ins: litmus.Instr) -> list[str] | None:
        op, q, a = ins.op, ins.quals, ins.args
        args = ", ".join(a)
        full = ".".join([op] + q)
        if op == "li":
            return [f"ld {args}"]
        if op in ("add", "sub", "mul"):
            return [ins.text]
        if op == "fence":
            if q == ["tso"]:
                return ["fence.acq_rel.sys"]
            if q == ["i"]:
                return []
            if not q and len(a) == 2 and all(FENCE_RW.match(x) for x in a):
                return [fence_kind(a[0], a[1])]
            return None
        m = re.fullmatch(r"(lb|lbu|lh|lhu|lw|lwu|ld)(\.aq|\.aqrl)?", full)
        if m:
            if m.group(2) == ".aqrl":
                return ["fence.sc.sys", f"ld.acquire.sys {args}"]
            return [f"ld.{'acquire.sys' if m.group(2) else 'weak'} {args}"]
        m = re.fullmatch(r"(sb|sh|sw|sd)(\.rl|\.aqrl)?", full)
        if m:
            if m.group(2) == ".aqrl":
                return ["fence.sc.sys", f"st.release.sys {args}"]
            return [f"st.{'release.sys' if m.group(2) else 'weak'} {args}"]
        m = re.fullmatch(r"amo(swap|add|and|or|xor|min|max|minu|maxu|cas)\.(b|h|w|d|q)(\.aq|\.rl|\.aqrl)?", full)
        if m:
            rop = {"swap": "exch", "minu": "min", "maxu": "max"}.get(m.group(1), m.group(1))
            width = ".b128" if m.group(2) == "q" else ""
            sem = {None: "relaxed", ".aq": "acquire", ".rl": "release", ".aqrl": "acq_rel"}[m.group(3)]
            if a and a[0] == "x0":   # the value read is discarded: a reduction (D34)
                body = f"red.{sem}.sys.{rop}{width} {', '.join(a[1:])}"
                if sem == "acquire" or sem == "acq_rel":
                    body = f"atom.{sem}.sys.{rop}{width} {args}"
            else:
                body = f"atom.{sem}.sys.{rop}{width} {args}"
            return (["fence.sc.sys"] if sem == "acq_rel" else []) + [body]
        if full == "cbo.inval":
            return [f"discard.global.L2 {a[0]}, 128"]
        if re.fullmatch(r"cbo\.(clean|flush)|prefetch\.(i|r|w)|ntl\.\w+|pause|wrs\.(nto|sto)", full):
            return []
        return None

    def kamui(self, ins: litmus.Instr) -> list[str]:
        q, a = ins.quals, ins.args
        parts = [ins.op] + q
        name = next((n for n in self.names if parts[:n.count(".") + 1] == n.split(".")), None)
        if name is None:
            raise Unsupported(f"unknown Kamui instruction {ins.text!r}")
        rest = parts[name.count(".") + 1:]
        ev = self.meaning[name]
        args = ", ".join(a)
        if ev == [] or ev is None:
            return []
        # Forms whose PTX operation depends on a qualifier, not only on the mnemonic.
        if name == "kldc":
            return [f"ld.{rest[0]} {args}"]
        if name in ("kmbar.arv", "kmbar.arv.drop", "kmbar.arv.expect_tx", "kmbar.expect_tx", "kmbar.complete_tx",
                    "kmbar.test", "kmbar.try", "kmbar.init", "kmbar.inval"):
            rest = ["shared::cluster" if x == "remote" else x for x in rest]
        if name == "kmbar.arv.ldgsts":
            return [f"cp.async.mbarrier.arrive{''.join('.' + x for x in rest)}.shared {args}"]
        if name == "kfence.proxy.async":
            sp = {"global": "global", "shared_cta": "shared::cta", "shared_cluster": "shared::cluster"}
            rest = [sp[x] for x in rest]
        if name == "kfence.proxy.tensormap":
            ev = "fence.proxy.tensormap::generic"
        if name == "kblkcp":
            d, mc = ".".join(rest[:2]), ("mc" in rest)
            body = {"s.g": "cp.async.bulk.shared::cluster.global.mbarrier::complete_tx::bytes",
                    "s.s": "cp.async.bulk.shared::cluster.shared::cta.mbarrier::complete_tx::bytes",
                    "g.s": "cp.async.bulk.global.shared::cta.bulk_group"}[d]
            return [f"{body}{'.multicast::cluster' if mc else ''} {args}"]
        if name == "kblkred":
            return [f"cp.reduce.async.bulk.global.shared::cta.bulk_group{''.join('.' + x for x in rest[2:])} {args}"]
        if name in ("ktmaldg", "ktmastg", "ktmaredg"):
            dim = [x for x in rest if re.fullmatch(r"\dd", x)]
            mode = [x for x in rest if x in ("tile", "im2col")]
            rop = [x for x in rest if x in to_alloy87.RMW_OPS]
            if name == "ktmaldg":
                mc = ".multicast::cluster" if "mc" in rest else ""
                return [f"cp.async.bulk.tensor.{dim[0]}.shared::cluster.global.{mode[0]}"
                        f".mbarrier::complete_tx::bytes{mc} {args}"]
            if name == "ktmastg":
                return [f"cp.async.bulk.tensor.{dim[0]}.global.shared::cta.{mode[0]}.bulk_group {args}"]
            return [f"cp.reduce.async.bulk.tensor.{dim[0]}.global.shared::cta.{rop[0]}.{mode[0]}.bulk_group {args}"]
        if name == "kstas":
            if "release" in rest:
                return [f"st.async{''.join('.' + x for x in rest)}.global {args}"]
            return [f"st.async.shared::cluster.mbarrier::complete_tx::bytes{''.join('.' + x for x in rest)} {args}"]
        if name == "kredas":
            if "release" in rest:
                return [f"red.async{''.join('.' + x for x in rest)}.global {args}"]
            rop = [x for x in rest if x in to_alloy87.RMW_OPS]
            other = [x for x in rest if x not in rop]
            return [f"red.async{''.join('.' + x for x in other)}.shared::cluster.mbarrier::complete_tx::bytes"
                    f"{''.join('.' + x for x in rop)} {args}"]
        if name == "kdepbar.bulk":
            return [f"cp.async.bulk.wait_group{''.join('.' + x for x in rest)} {args}"]
        if name in ("kldsm", "kstsm"):
            return [f"{ev.split('.')[0]}.sync.aligned{''.join('.' + x for x in rest)}.shared.b16 {args}"]
        if name in ("kldgmc", "kstgmc", "kredgmc"):
            base, kind = ev.split(".")[0], ev.split(".")[1]
            return [f"{base}.{kind}{''.join('.' + x for x in rest)}.global {args}"]
        if name == "kgmma":
            return [f"wgmma.mma_async.sync.aligned{''.join('.' + x for x in rest)} {args}"]
        if name.startswith("kwarpgroup"):
            return [f"{ev}.sync.aligned {args}".strip()]
        if isinstance(ev, list):
            return list(ev)
        return [f"{ev}{''.join('.' + x for x in rest)} {args}".strip()]

    def instr(self, ins: litmus.Instr) -> list[str]:
        if ins.is_empty:
            return []
        s = self.std(ins)
        if s is not None:
            return s
        return self.kamui(ins)

    def expand(self, t: litmus.Litmus) -> tuple[litmus.Litmus, dict]:
        """The PTX-dialect program with the events of the Kamui test, and the declared location spaces."""
        spaces, init = {}, []
        for d in t.init:
            m = re.fullmatch(r"(\w+)\s+in\s+(global|shared|local|const|param)(?:\s+cta\s+(\d+))?(?:\s+P(\d+))?",
                             d.strip())
            if m:
                spaces[m.group(1)] = (m.group(2), m.group(3), m.group(4))
            else:
                init.append(d)
        threads = []
        for th in t.threads:
            instrs = []
            for ins in th.instrs:
                for text in self.instr(ins):
                    instrs.append(litmus.parse_instr(text))
            threads.append(litmus.Thread(th.tid, th.cta, th.gpu, th.cluster, instrs=instrs, grid=th.grid))
        u = litmus.Litmus("PTX", t.name, t.comments, init, threads, t.quantifier, t.cond_text, t.condition)
        return u, spaces


class KamuiQuery(to_alloy87.Query):
    """A query against models/kamui/kamui.als, with location spaces taken from the test's declarations."""

    def __init__(self, t, name, spaces, src):
        super().__init__(t, name)
        self.spaces, self.src = spaces, src

    def parse_init(self):
        super().parse_init()
        for name, (sp, cta, tid) in self.spaces.items():
            loc = self.locs.setdefault(name, to_alloy87.Loc(name, [f"L_{name}"], [0]))
            loc.space = {"global": "Global", "shared": "Shared", "local": "Local", "const": "Const",
                         "param": "Param"}[sp]
            if cta is not None:
                loc.owner_cta = int(cta)
            if tid is not None:
                loc.owner = f"T{tid}"

    def emit(self) -> str:
        s = super().emit()
        s = s.replace("\nopen ptx87\n", "\nopen kamui\n", 1)
        return HEADER.format(test=self.src) + s.split("\n", 1)[1]


def translate_kamui(t: litmus.Litmus, name: str, src: str) -> str:
    u, spaces = Expander().expand(t)
    q = KamuiQuery(u, name, spaces, src)
    q.pdirs, q.pspace, q.paddr, q.txops = {}, {}, {}, {}
    q.open_arrive = {}
    q.build()
    return q.emit()


