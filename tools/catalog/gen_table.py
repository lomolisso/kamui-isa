#!/usr/bin/env python3
"""Generate spec/ptx-table.md, the two-way table between PTX and Kamui, from tests/corpus/catalog.yaml.

The PTX side (one row per in-scope catalog feature, grouped by extension family) is generated. The Kamui
columns stay empty until the instructions are specified; they will then be filled from the catalog as well.

    python tools/catalog/gen_table.py            # rewrite spec/ptx-table.md
    python tools/catalog/gen_table.py --check    # fail if spec/ptx-table.md is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402

FAMILY_TITLES = {
    "base": "Base ISA (plain RV64 suffices)",
    "Xkmsimt": "Xkmsimt: threads, warps, predication, special registers",
    "Xkmwarp": "Xkmwarp: warp-level operations",
    "Xkmbar": "Xkmbar: CTA and cluster barriers",
    "Xkmscope": "Xkmscope: scoped and ordered memory operations",
    "Xkmmbar": "Xkmmbar: mbarrier objects",
    "Xkmasync": "Xkmasync: asynchronous copies and TMA",
    "Xkmmma": "Xkmmma: matrix multiply-accumulate",
    "Xkmcluster": "Xkmcluster: clusters and distributed shared memory",
    "Xkmmufu": "Xkmmufu: approximate math functions",
    "Xkmmisc": "Xkmmisc: bit manipulation, packed and narrow formats, hints",
}

HEADER = """\
# PTX to Kamui table

<!-- Generated by tools/catalog/gen_table.py from tests/corpus/catalog.yaml. Do not edit by hand. -->

This is the two-way table between PTX and the Kamui ISA:

- every in-scope PTX feature (instruction, modifier, state space, special register, directive) has a row that
  names its Kamui lowering, a bounded sequence of Kamui instructions;
- every Kamui instruction names the PTX construct that justifies it.

The PTX side comes from the feature catalog `tests/corpus/catalog.yaml`. The Kamui columns are empty until the
instructions are specified. Columns:

| Column | Meaning |
|---|---|
| Feature | Catalog id |
| PTX syntax | Canonical form, from the PTX ISA 8.7 manual |
| Section | Section of the PTX ISA 8.7 manual |
| Tier | Kamui tier (1 to 4) that implements the feature |
| Route | How CUDA code reaches it: `cuda` (plain CUDA C++), `builtin` (clang `__nvvm_*` builtin), `llvm-ir` (only an LLVM intrinsic), `inline-asm` |
| Corpus | Directory of the micro-kernel in `tests/corpus/` |
| Kamui lowering | The Kamui instruction sequence |
| Kamui instructions | The Kamui instructions it uses |
"""


def cell(text: str) -> str:
    return str(text or "").replace("|", "\\|").replace("\n", " ")


def code(text: str) -> str:
    text = cell(text)
    return f"`{text}`" if text else ""


def render(rows: list[dict]) -> str:
    out = [HEADER]
    in_scope = [r for r in rows if r["status"] == "in-scope"]
    excluded = [r for r in rows if r["status"] == "excluded"]
    out.append("## PTX to Kamui\n")
    out.append(f"{len(in_scope)} in-scope features in {len({r['family'] for r in in_scope})} families.\n")
    for fam in common.FAMILIES:
        fr = sorted((r for r in in_scope if r["family"] == fam), key=lambda r: (r["tier"], r["id"]))
        if not fr:
            continue
        out.append(f"### {FAMILY_TITLES[fam]}\n")
        out.append("| Feature | PTX syntax | Section | Tier | Route | Corpus | Kamui lowering | Kamui instructions |")
        out.append("|---|---|---|---|---|---|---|---|")
        for r in fr:
            sec = r.get("manual_section", "").split(" ", 1)[0]
            entry = r.get("entry") or ""
            entry = "pending" if entry == "pending" else (code(entry.removeprefix("tests/corpus/")) if entry else "")
            out.append(f"| {code(r['id'])} | {code(r.get('ptx_syntax'))} | {sec} | {r['tier']} | {r.get('route', '')} "
                       f"| {entry} |  |  |")
        out.append("")
    out.append("## Kamui to PTX\n")
    out.append("Filled when the first Kamui instruction is specified: one row per Kamui instruction, with the PTX "
               "features that justify it.\n")
    out.append("## Excluded PTX features\n")
    out.append(f"{len(excluded)} features of PTX 8.7 are out of scope. They stay in the catalog so the coverage "
               "checks can tell an exclusion from an omission.\n")
    out.append("| Feature | Section | Reason |")
    out.append("|---|---|---|")
    for r in sorted(excluded, key=lambda r: r["id"]):
        sec = r.get("manual_section", "").split(" ", 1)[0]
        out.append(f"| {code(r['id'])} | {sec} | {cell(r.get('exclusion_reason'))} |")
    out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if the table is out of date")
    ap.add_argument("--catalog", type=Path, default=common.CATALOG)
    ap.add_argument("--output", type=Path, default=common.TABLE)
    args = ap.parse_args(argv)
    text = render(common.load_catalog(args.catalog))
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != text:
            print(f"{args.output} is out of date: run python tools/catalog/gen_table.py", file=sys.stderr)
            return 1
        print(f"{args.output} is up to date")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
