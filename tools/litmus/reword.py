#!/usr/bin/env python3
"""Generate the rewording mutants of the PTX 8.7 Alloy model (models/ptx87/mutants-reword.yaml).

The hand-written mutants of mutants.yaml each delete a rule. A rule can also be written slightly wrong: a missing
transitive closure (`co` for `^co`, the bug fixed by D42), a missing transpose, a dropped domain restriction, `&`
for `+`. This script makes one mutant per such change, for every occurrence in the body of every `fun` and `pred`
of ptx87.als (facts are not mutated), and writes them in the format of mutants.yaml, so tools/litmus/mutate.py runs
them like the others:

    python tools/litmus/reword.py            # rewrite models/ptx87/mutants-reword.yaml
    python tools/litmus/reword.py --check    # fail if the file is not up to date

The operators: drop `^`, `*` or `~`; drop `S <:` or `:> S`; `&` to `+` and `+` to `&`; drop the right side of
`-`; `optional[r]` to `r`; `strong[r]` to `r`; `same_alias` to `same_location` and back.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODEL = ROOT / "models" / "ptx87" / "ptx87.als"
OUT = ROOT / "models" / "ptx87" / "mutants-reword.yaml"

OPERAND = r"(?:[A-Za-z_][\w.]*|\([^()]*\))"
OPS = [
    ("closure", r"\^(?=[\w(~*])", lambda m: ""),
    ("refl-closure", r"(?<![\w)\]])\*(?=[\w(~^])", lambda m: ""),
    ("transpose", r"~(?=[\w(^*])", lambda m: ""),
    ("domain", rf"{OPERAND} <: ", lambda m: ""),
    ("range", rf" :> {OPERAND}", lambda m: ""),
    ("and-to-or", r" & ", lambda m: " + "),
    ("or-to-and", r" \+ ", lambda m: " & "),
    ("minus", rf" - {OPERAND}(?![\w.\[(]|->| <:| :>)", lambda m: ""),   # a whole operand only
    ("optional", r"optional\[([^\[\]]*)\]", lambda m: f"({m.group(1)})"),
    ("strong", r"(?<![\w_])strong\[([^\[\]]*)\]", lambda m: f"({m.group(1)})"),
    ("alias-to-location", r"same_alias\[", lambda m: "same_location["),
    ("location-to-alias", r"same_location\[", lambda m: "same_alias["),
]


def bodies(text):
    """(definition name, line index) for every code line inside a fun or pred body."""
    lines = text.split("\n")
    out, name, depth, opened = [], None, 0, False
    for i, line in enumerate(lines):
        code = line.split("//")[0]
        if name is None:
            m = re.match(r"^(?:fun|pred)\s+(\w+)", code)
            if not m:
                continue
            name, depth, opened = m.group(1), 0, False
        out.append((name, i))
        depth += code.count("{") - code.count("}")
        opened = opened or "{" in code
        if opened and depth <= 0:
            name = None
    return lines, out


def generate():
    text = MODEL.read_text()
    lines, where = bodies(text)
    mutants, seen = [], set()
    for name, i in where:
        line = lines[i]
        code, sep, comment = line.partition("//")
        # on the line that declares the definition, only its body (after the first `{`) is mutated
        head = code.index("{") + 1 if re.match(r"^(?:fun|pred)\s", code) and "{" in code else 0
        for op, pat, rep in OPS:
            for k, m in enumerate(x for x in re.finditer(pat, code) if x.start() >= head):
                new_code = code[:m.start()] + rep(m) + code[m.end():]
                new = new_code + sep + comment
                if new == line:
                    continue
                find, replace = line + "\n", new + "\n"
                j = i
                while text.count(find) != 1 and j > 0:   # widen the context until the text is unique
                    j -= 1
                    find, replace = lines[j] + "\n" + find, lines[j] + "\n" + replace
                if text.count(find) != 1:
                    continue
                mid = f"R-{name}-{op}-{i + 1}" + (f"-{k + 1}" if k else "")
                if mid in seen:
                    continue
                seen.add(mid)
                mutants.append({"id": mid, "rule": f"{name} (line {i + 1}): {op}", "find": find,
                                "replace": replace})
    return mutants


def dump(mutants):
    def q(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
    out = ["# Rewording mutants of models/ptx87/ptx87.als, generated by tools/litmus/reword.py; do not edit.",
           "# Each changes one occurrence of an operator in the body of a fun or pred (see the script). Run with",
           "# tools/litmus/mutate.py like the mutants of mutants.yaml.", ""]
    for m in mutants:
        out += [f"- id: {m['id']}", "  model: alloy", "  kind: reword", f"  rule: {q(m['rule'])}",
                f"  find: {q(m['find'])}", f"  replace: {q(m['replace'])}"]
    return "\n".join(out) + "\n"


def main():
    text = dump(generate())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is not up to date: run tools/litmus/reword.py")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count('- id:')} mutants)")


if __name__ == "__main__":
    main()
