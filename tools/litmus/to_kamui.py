def ptx_tests() -> list[Path]:
    return sorted((SUITE / "ptx").rglob("*.litmus"))


def hand_tests() -> list[Path]:
    return sorted((KTESTS / "hand").rglob("*.litmus"))


def tid_of(p: Path) -> str:
    return p.relative_to(SUITE).with_suffix("").as_posix()


def kamui_path(tid: str, variant: str) -> Path:
    """The lowered test of PTX test `tid` (ptx/...)."""
    return KTESTS / variant / (tid.removeprefix("ptx/") + ".litmus")


def query_path(tid: str, variant: str) -> Path:
    if variant == "hand":
        return OUT / (tid.removeprefix("kamui-isa/") + ".als")
    return OUT / variant / (tid.removeprefix("ptx/") + ".als")


def lower(t: litmus.Litmus, variant: str, broken: str | None = None, src: str = "?") -> tuple[str, Counter]:
    lw = Lowerer(t, variant, broken, src)
    return lw.lower_test(), lw.used


def generate() -> tuple[dict[Path, str], dict[str, str], Counter]:
    files, skipped, used = {}, {}, Counter()
    for p in ptx_tests():
        tid = tid_of(p)
        t = litmus.load(p)
        for v in VARIANTS:
            try:
                text, u = lower(t, v, src=tid)
                kt = litmus.parse(text)
                kpath = kamui_path(tid, v)
                q = translate_kamui(kt, re.sub(r"[^A-Za-z0-9_]", "_", tid), tid_of(kpath))
            except (Unsupported, litmus.LitmusError, KeyError, StopIteration, IndexError) as e:
                skipped[f"{tid} [{v}]"] = str(e) or type(e).__name__
                continue
            if v == "kamui":
                used += u
            files[kpath] = text
            files[query_path(tid, v)] = q
    for p in hand_tests():
        tid = tid_of(p)
        try:
            files[query_path(tid, "hand")] = translate_kamui(litmus.load(p), re.sub(r"[^A-Za-z0-9_]", "_", tid), tid)
        except Unsupported as e:
            skipped[tid] = str(e)
    return files, skipped, used


def kamui_query_for(tid: str, model: str) -> Path | None:
    """The query run_formal.py runs for test `tid` under model `model`, or None."""
    if tid.startswith("kamui-isa/hand/"):
        return query_path(tid, "hand") if model == "kamui-alloy" else None
    v = {"kamui-alloy": "kamui", "kamui-std-alloy": "std"}[model]
    p = query_path(tid, v)
    return p if p.exists() else None


