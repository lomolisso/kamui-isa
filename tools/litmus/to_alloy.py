#!/usr/bin/env python3
"""Translate litmus tests into Alloy queries against the 2019 PTX memory model (deps/ptx-memory-model/ptx.als).

    python tools/litmus/to_alloy.py            # write tests/litmus/alloy/<test>.als for every test it can express
    python tools/litmus/to_alloy.py --check    # fail if a committed .als file is missing, stale or orphaned
    python tools/litmus/to_alloy.py --why      # print every test it cannot express, with the reason

The 2019 model (Lustig, Sahasrabuddhe and Giroux, ASPLOS 2019; PTX ISA 6.0) describes an execution by its events
and relations: program order `po`, reads-from `rf`, coherence `co`, the scope tree `subscope`, and each event's
`scope`. It has no data values. A test is therefore expressed as a fixed set of events (`one sig` atoms) plus a
`fact shape` that pins the program, and the condition is rewritten in terms of `rf`: `P1:r0 == 1`, where r0 was
loaded from x, becomes "the read of x reads from the write of 1 to x"; `== 0` (the initial value) becomes "reads
from no write". Alloy then searches for an execution that satisfies the model (`ptx_mm`) and the condition:
an instance means **allowed**, no instance means **forbidden** (within the bound, which covers every event).

What it can express: loads and stores (weak, relaxed, acquire, release) with constant values, `fence.sc`,
`fence.acq_rel`, `bar.cta.sync <id>` (the model's arrive and wait events; the k-th barrier of each thread of a
CTA synchronizes with the k-th of the others), conditions on registers and on final memory values (the final
value is that of the write every other write to the location precedes in coherence order), and, as our extension, `fence.acquire`/`fence.release` (mapped to the model's FenceAcq and
FenceRel) and the `.cluster` scope (an extra level in the scope tree: system > gpu > cluster > cta > thread).
It skips proxies, read-modify-writes (their written value depends on what they read), barriers with a thread
count or a register operand, loops, and stores of loaded values (`--why` lists each skipped test).

Scopes: a weak access gets its own thread as scope (in the model, a thread-scoped access is not strong); a
`.cta` access gets its thread's CTA node, `.cluster` the cluster node, `.gpu` the GPU node, `.sys` the root.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import litmus  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SUITE = ROOT / "tests" / "litmus"
OUT = SUITE / "alloy"
HEADER = "// Generated by tools/litmus/to_alloy.py from tests/litmus/{test}.litmus. Do not edit.\n"


class Unsupported(Exception):
    pass


FENCE_SIG = {"sc": "FenceSC", "acq_rel": "FenceAcqRel", "acquire": "FenceAcq", "release": "FenceRel"}


def model_name(t: litmus.Litmus) -> str:
    """`ptx-2019-alloy` for PTX 6.0 features, `ptx-2019-alloy+ext` when our extensions are used."""
    ext = t.uses_cluster_scope or t.uses_ptx86_fences
    return "ptx-2019-alloy+ext" if ext else "ptx-2019-alloy"


def _const(v: str) -> int | None:
    try:
        return int(v, 0)
    except ValueError:
        return None


def translate(t: litmus.Litmus, name: str) -> str:
    if t.uses_proxy:
        raise Unsupported("proxies (the 2019 model has none)")
    if t.has_loops:
        raise Unsupported("loops")
    for d in t.init:
        if ":" not in d.split("=")[0] and _const(d.split("=", 1)[1].strip()) is None:
            raise Unsupported(f"initial state {d!r}")
    init_val = {}
    for d in t.init:
        lhs, rhs = (s.strip() for s in d.split("=", 1))
        if ":" not in lhs:
            init_val[lhs] = _const(rhs)
    clusters = any(th.cluster is not None for th in t.threads)
    if t.uses_cluster_scope and not all(th.cluster is not None for th in t.threads):
        raise Unsupported("a .cluster scope needs every thread placed in a cluster")

    # ---- scope tree
    tree: list[tuple[str, str]] = []
    scopes = ["Sys"]
    node_of: dict[tuple[int, str], str] = {}
    cta_parent: dict[str, str] = {}
    barriers: dict[tuple[str, str], dict[int, list[tuple[str, str]]]] = {}

    def add(child, parent):
        if child not in scopes:
            scopes.append(child)
            tree.append((parent, child))

    # ---- events
    events: list[tuple[str, str]] = []  # (atom, sig)
    po, start, address, scope = [], [], [], []
    reads: dict[str, tuple[str, str]] = {}  # "P1:r0" -> (read atom, location)
    consts: dict[str, int] = {}  # "P1:r0" -> constant value
    writes: dict[str, list[tuple[str, int]]] = {}
    threads_used = []
    for th in t.threads:
        g = f"Gpu{th.gpu}"
        add(g, "Sys")
        parent = g
        if clusters:
            c = f"Cl{th.gpu}_{th.cluster}"
            add(c, g)
            parent = c
        cta = f"Cta{th.gpu}_{th.cta}"
        if cta_parent.setdefault(cta, parent) != parent:
            raise Unsupported(f"CTA {th.cta} placed in two clusters")
        add(cta, parent)
        tnode = f"T{th.tid}"
        node_of.update({(th.tid, "cta"): cta, (th.tid, "gpu"): g, (th.tid, "sys"): "Sys"})
        if clusters:
            node_of[(th.tid, "cluster")] = parent
        prev = None
        mine = []
        for ins in th.instrs:
            if ins.is_empty:
                continue
            reg_key = lambda r: f"P{th.tid}:{r}"  # noqa: E731
            if ins.op == "ld" and not ins.quals:
                if len(ins.args) != 2 or _const(ins.args[1]) is None:
                    raise Unsupported(f"instruction {ins.text!r}")
                consts[reg_key(ins.args[0])] = _const(ins.args[1])
                continue
            if any("::" in q for q in ins.quals):
                raise Unsupported(f"state-space restricted instruction {ins.text!r} (the model has no state spaces)")
            atom = f"E{len(events)}"
            if ins.op == "ld":
                order = ins.order
                if order not in ("weak", "relaxed", "acquire"):
                    raise Unsupported(f"instruction {ins.text!r}")
                sig = "Acquire" if order == "acquire" else "Read"
                r, loc = ins.args
                k = reg_key(r)
                if k in reads or k in consts:
                    raise Unsupported(f"register {k} written twice")
                reads[k] = (atom, loc)
                address.append(f"{atom}->L_{loc}")
            elif ins.op == "st":
                order = ins.order
                if order not in ("weak", "relaxed", "release"):
                    raise Unsupported(f"instruction {ins.text!r}")
                sig = "Release" if order == "release" else "Write"
                loc, val = ins.args
                v = _const(val)
                if v is None:
                    v = consts.get(reg_key(val))
                if v is None:
                    raise Unsupported(f"store of a loaded register {ins.text!r}")
                writes.setdefault(loc, []).append((atom, v))
                address.append(f"{atom}->L_{loc}")
            elif ins.op == "fence" and ins.order in FENCE_SIG:
                sig, order = FENCE_SIG[ins.order], ins.order
            elif ins.op == "bar" and ins.quals == ["cta", "sync"] and len(ins.args) == 1 and _const(ins.args[0]) is not None:
                # bar.sync = an arrive followed by a wait (the model's encoding); paired up below
                arrive, wait = atom, f"E{len(events) + 1}"
                for a, sg in ((arrive, "BarrierArrive"), (wait, "BarrierWait")):
                    events.append((a, sg))
                    scope.append(f"{a}->{cta}")
                    mine.append(a)
                    if prev:
                        po.append(f"{prev}->{a}")
                    prev = a
                barriers.setdefault((cta, ins.args[0]), {}).setdefault(th.tid, []).append((arrive, wait))
                continue
            else:
                raise Unsupported(f"instruction {ins.text!r}")
            if ins.op in ("ld", "st") and order == "weak":
                sc = tnode
            else:
                s = ins.scope
                if s is None or (th.tid, s) not in node_of:
                    raise Unsupported(f"scope of {ins.text!r}")
                sc = node_of[(th.tid, s)]
            scope.append(f"{atom}->{sc}")
            events.append((atom, sig))
            mine.append(atom)
            if prev:
                po.append(f"{prev}->{atom}")
            prev = atom
        if mine:
            add(tnode, cta)
            start.append(f"{tnode}->{mine[0]}")
            threads_used.append(tnode)
    # A thread node with no events would break `start: one Event`; such threads only hold constants.
    scopes = [s for s in scopes if not re.fullmatch(r"T\d+", s) or s in threads_used]

    sync = []
    for (cta, bid), per_thread in barriers.items():
        counts = {len(v) for v in per_thread.values()}
        if len(counts) != 1:
            raise Unsupported(f"barrier {bid} used a different number of times by the threads of {cta}")
        for k in range(counts.pop()):
            group = [v[k] for v in per_thread.values()]
            sync += [f"{a}->{w}" for a, _ in group for _, w in group]

    locs = sorted({a.split("->L_")[1] for a in address})
    for loc in locs:
        n = sum(1 for a in address if a.endswith(f"->L_{loc}"))
        if n < 2 or not writes.get(loc):
            raise Unsupported(f"location {loc} needs at least two accesses and a write (model fact on Address)")

    # ---- condition
    def atom_formula(c: litmus.Cmp) -> str:
        lhs, rhs = c.lhs, c.rhs
        if _const(lhs) is not None and _const(rhs) is None:
            lhs, rhs = rhs, lhs
        if re.fullmatch(r"\d+:\w+", lhs):
            lhs = "P" + lhs
        v = _const(rhs)
        if v is None:
            raise Unsupported(f"condition {c}")
        if c.op not in ("==", "!="):
            raise Unsupported(f"condition {c}")
        if lhs in consts:
            f = "(no none)" if consts[lhs] == v else "(some none)"
        elif lhs in reads:
            r, loc = reads[lhs]
            ws = [w for w, wv in writes.get(loc, []) if wv == v]
            parts = []
            if init_val.get(loc, 0) == v:
                parts.append(f"no rf.{r}")
            if ws:
                parts.append(f"{r} in ({' + '.join(ws)}).rf")
            f = "(" + " or ".join(parts) + ")" if parts else "(some none)"
        elif lhs in locs:
            # final value: the write that every other write to the location precedes in coherence order
            ws_all = [w for w, _ in writes[lhs]]
            parts = []
            for w, wv in writes[lhs]:
                if wv == v:
                    others = [o for o in ws_all if o != w]
                    parts.append(f"({' + '.join(others)}) in ^co.{w}" if others else "(no none)")
            f = "(" + " or ".join(parts) + ")" if parts else "(some none)"
        else:
            raise Unsupported(f"condition on {lhs} (not a loaded register)")
        return f if c.op == "==" else f"(not {f})"

    def formula(e) -> str:
        if isinstance(e, litmus.Cmp):
            return atom_formula(e)
        if isinstance(e, litmus.Not):
            return f"(not {formula(e.arg)})"
        op = " and " if isinstance(e, litmus.And) else " or "
        return "(" + op.join(formula(a) for a in e.args) + ")"

    cond = formula(t.condition)
    n = max(len(events), len(scopes), len(locs), 1)

    lines = [f"module {re.sub(r'[^A-Za-z0-9_]', '_', name)}", "open ptx", ""]
    for line in t.format().splitlines():
        lines.append(f"// {line}")
    lines.append("")
    lines.append(f"one sig {', '.join(s for s in scopes if not s.startswith('T'))} extends Scope {{}}")
    lines.append(f"one sig {', '.join(threads_used)} extends Thread {{}}")
    lines.append(f"one sig {', '.join('L_' + loc for loc in locs)} extends Address {{}}")
    for sig in sorted({s for _, s in events}):
        lines.append(f"one sig {', '.join(a for a, s in events if s == sig)} extends {sig} {{}}")
    lines += [
        "",
        "fact shape {",
        f"  Event = {' + '.join(a for a, _ in events)}",
        f"  Scope = {' + '.join(scopes)}",
        f"  Address = {' + '.join('L_' + loc for loc in locs)}",
        f"  subscope = {' + '.join(f'{p}->{c}' for p, c in tree if c in scopes)}",
        f"  start = {' + '.join(start)}",
        f"  po = {' + '.join(po) if po else 'none->none'}",
        f"  address = {' + '.join(address)}",
        f"  scope = {' + '.join(scope)}",
        "  no dep",
        "  no rmw",
        f"  synchronizes = {' + '.join(sync)}" if sync else "  no synchronizes",
        "}",
        "",
        f"pred outcome {{ {cond} }}",
        "",
        f"run test {{ ptx_mm and outcome }} for {n}",
        "",
    ]
    return HEADER.format(test=name) + "\n".join(lines)


def tests() -> list[Path]:
    return sorted((SUITE / "ptx").rglob("*.litmus"))


def test_id(p: Path) -> str:
    return p.relative_to(SUITE).with_suffix("").as_posix()


def als_path(tid: str) -> Path:
    return OUT / (tid.removeprefix("ptx/") + ".als")


def generate() -> tuple[dict[Path, str], dict[str, str]]:
    files, skipped = {}, {}
    for p in tests():
        tid = test_id(p)
        try:
            files[als_path(tid)] = translate(litmus.load(p), tid)
        except Unsupported as e:
            skipped[tid] = str(e)
    return files, skipped


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--why", action="store_true")
    a = ap.parse_args()
    files, skipped = generate()
    if a.why:
        for tid, why in sorted(skipped.items()):
            print(f"{tid}: {why}")
    if a.check:
        bad = [p for p, s in files.items() if not p.exists() or p.read_text() != s]
        extra = sorted(set(OUT.rglob("*.als")) - set(files)) if OUT.exists() else []
        for p in bad:
            print(f"stale or missing: {p.relative_to(ROOT)}")
        for p in extra:
            print(f"orphaned: {p.relative_to(ROOT)}")
        print(f"{len(files)} queries, {len(bad)} stale, {len(extra)} orphaned")
        return 1 if bad or extra else 0
    for p in set(OUT.rglob("*.als")) - set(files) if OUT.exists() else []:
        p.unlink()
    for p, s in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(s)
    print(f"wrote {len(files)} queries, skipped {len(skipped)} tests", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
